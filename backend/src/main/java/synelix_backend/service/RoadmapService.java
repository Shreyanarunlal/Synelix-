package synelix_backend.service;

import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import synelix_backend.entity.RoadmapTask;
import synelix_backend.entity.StudentProfile;
import synelix_backend.exception.ResourceNotFoundException;
import synelix_backend.ml.MlClient;
import synelix_backend.ml.ProfilePayload;
import synelix_backend.repository.RoadmapTaskRepository;
import synelix_backend.repository.StudentProfileRepository;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

/**
 * Personalised roadmap.
 *
 * <p>The plan itself is generated by the ML service from the student's own
 * skill gaps. Completion state lives here, keyed by task id, and is passed
 * back into generation so ticking a task survives the plan being rebuilt
 * after a profile change.</p>
 */
@Service
public class RoadmapService {

    private final RoadmapTaskRepository roadmapTaskRepository;
    private final StudentProfileRepository studentProfileRepository;
    private final MlClient mlClient;

    public RoadmapService(RoadmapTaskRepository roadmapTaskRepository,
                          StudentProfileRepository studentProfileRepository,
                          MlClient mlClient) {
        this.roadmapTaskRepository = roadmapTaskRepository;
        this.studentProfileRepository = studentProfileRepository;
        this.mlClient = mlClient;
    }

    public Map<String, Object> getRoadmap(String email, String targetRole) {
        StudentProfile profile = requireProfile(email);
        Map<String, Boolean> completed = completionState(email);

        String role = targetRole != null && !targetRole.isBlank()
                ? targetRole : profile.getTargetRole();

        return mlClient.roadmap(ProfilePayload.from(profile), role, completed)
                .map(body -> withSource(body, PredictionService.SOURCE_ML))
                .orElseGet(() -> fallbackRoadmap(completed));
    }

    @Transactional
    public Map<String, Object> toggleTask(String email, String taskId, Boolean done) {
        requireProfile(email);
        if (taskId == null || taskId.isBlank()) {
            throw new ResourceNotFoundException("A task id is required");
        }

        Optional<RoadmapTask> existing =
                roadmapTaskRepository.findByUserEmailAndTaskId(email, taskId);

        RoadmapTask task = existing.orElseGet(
                () -> new RoadmapTask(email, "generated", taskId, taskId, false));

        boolean current = Boolean.TRUE.equals(task.getDone());
        task.setDone(done != null ? done : !current);
        roadmapTaskRepository.save(task);

        Map<String, Object> result = new HashMap<>();
        result.put("taskId", task.getTaskId());
        result.put("done", task.getDone());
        result.put("success", true);
        result.put("message", "Task " + taskId + " marked "
                + (Boolean.TRUE.equals(task.getDone()) ? "complete" : "incomplete"));
        return result;
    }

    private Map<String, Boolean> completionState(String email) {
        Map<String, Boolean> completed = new HashMap<>();
        for (RoadmapTask task : roadmapTaskRepository.findByUserEmail(email)) {
            completed.put(task.getTaskId(), Boolean.TRUE.equals(task.getDone()));
        }
        return completed;
    }

    private StudentProfile requireProfile(String email) {
        if (email == null || email.isBlank()) {
            throw new ResourceNotFoundException("A student email is required");
        }
        return studentProfileRepository.findByEmail(email)
                .orElseThrow(() -> new ResourceNotFoundException(
                        "No student profile found for " + email));
    }

    private Map<String, Object> withSource(Map<String, Object> body, String source) {
        Map<String, Object> result = new LinkedHashMap<>(body);
        result.put("modelSource", source);
        return result;
    }

    /**
     * Generic preparation plan used only when the ML service is unreachable.
     *
     * <p>It is explicitly labelled as not personalised, because the whole
     * value of the roadmap is that it targets the student's own gaps.</p>
     */
    private Map<String, Object> fallbackRoadmap(Map<String, Boolean> completed) {
        String[][] phases = {
                {"Week 1 - 2", "Core DSA & Problem Solving",
                        "Master Array, Two-Pointer and Sliding Window patterns",
                        "HashMaps, Prefix Sums and Stack problems",
                        "Quantitative aptitude: Time and Work, Speed and Distance"},
                {"Week 3 - 4", "Trees, Graphs & Dynamic Programming",
                        "Binary Tree and BST traversals, lowest common ancestor",
                        "Graph BFS/DFS and Dijkstra",
                        "Dynamic Programming: knapsack and subsequence patterns"},
                {"Week 5 - 6", "System Design & Proof of Work",
                        "Low-level design: SOLID principles and design patterns",
                        "High-level design: caching, sharding, load balancing",
                        "Deploy a full-stack project with Docker and CI/CD"},
                {"Week 7 - 8", "Mock Interviews & ATS Optimisation",
                        "Behavioural interview practice with the STAR method",
                        "Two full-length timed placement mock tests",
                        "Final ATS resume audit and recruiter showcase"},
        };

        List<Map<String, Object>> result = new ArrayList<>();
        int counter = 1;
        int totalTasks = 0;
        int doneTasks = 0;

        for (String[] phase : phases) {
            List<Map<String, Object>> tasks = new ArrayList<>();
            for (int i = 2; i < phase.length; i++) {
                String taskId = "t" + counter++;
                boolean isDone = completed.getOrDefault(taskId, false);
                totalTasks++;
                if (isDone) {
                    doneTasks++;
                }
                Map<String, Object> task = new LinkedHashMap<>();
                task.put("id", taskId);
                task.put("title", phase[i]);
                task.put("done", isDone);
                tasks.add(task);
            }

            long completedInPhase = tasks.stream()
                    .filter(t -> Boolean.TRUE.equals(t.get("done"))).count();
            int percent = (int) Math.round(100.0 * completedInPhase / tasks.size());

            Map<String, Object> entry = new LinkedHashMap<>();
            entry.put("week", phase[0]);
            entry.put("phase", phase[1]);
            entry.put("tasks", tasks);
            entry.put("status", percent == 100 ? "completed"
                    : completedInPhase > 0 ? "in-progress" : "upcoming");
            entry.put("badge", percent == 100 ? "100% Done"
                    : completedInPhase > 0 ? percent + "% Done" : "Upcoming");
            result.add(entry);
        }

        Map<String, Object> response = new LinkedHashMap<>();
        response.put("phases", result);
        response.put("totalTasks", totalTasks);
        response.put("completedTasks", doneTasks);
        response.put("progressPercent", totalTasks == 0 ? 0
                : (int) Math.round(100.0 * doneTasks / totalTasks));
        response.put("modelSource", PredictionService.SOURCE_FALLBACK);
        response.put("notice", "This is the standard preparation plan, not a personalised one. "
                + "Start the ML service to generate a roadmap from your own skill gaps.");
        return response;
    }
}
